package dev.mcbench.probe.core;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.net.URL;
import java.nio.file.Path;
import java.util.List;
import org.junit.jupiter.api.Test;

/**
 * Verifies the join between the harness and the probe.
 *
 * <p>The plan format has two sides: Python writes it in {@code src/mcbench/runner/plan.py} and
 * Java reads it in {@link ProbeConfig}. That seam was broken once — the harness wrote a scenario
 * JSON the probe had no parser for, so the probe would never have started, and nothing in either
 * test suite noticed because each side was individually correct.
 *
 * <p>The fixture here was generated by the real Python compiler, not hand-written. Regenerate it
 * with the snippet in {@code tests/test_plan.py}. If a change to either side breaks these, the
 * harness and the probe have stopped agreeing about how a scenario is handed over.
 */
class PlanJoinTest {

    private Path fixture(String name) throws Exception {
        URL url = getClass().getClassLoader().getResource("plan-fixture/" + name);
        assertNotNull(url, "missing fixture plan-fixture/" + name);
        return Path.of(url.toURI());
    }

    private ProbeConfig load() throws Exception {
        return ProbeConfig.load(fixture("probe.properties"));
    }

    @Test
    void javaReadsThePythonGeneratedProperties() throws Exception {
        ProbeConfig config = load();
        assertEquals("join-fixture", config.scenarioId());
        assertEquals("1.0.0", config.scenarioVersion());
        assertEquals(ProbeConfig.Side.SERVER, config.side());
        assertFalse(config.contentHash().isEmpty(), "content hash must survive the handover");
    }

    @Test
    void methodologySettingsSurviveTheHandover() throws Exception {
        ProbeConfig config = load();
        // These drive phase control. If they arrived wrong the run would still
        // produce numbers, measured over the wrong window.
        assertEquals(2000.0, config.warmupMinimum());
        assertEquals(12000.0, config.measurementDuration());
        assertEquals(200, config.steadyStateWindow());
        assertTrue(config.tickWarp());
        assertFalse(config.saturated());
    }

    @Test
    void commandListsAreLoadedAlongsideTheProperties() throws Exception {
        ProbeConfig config = load();
        assertFalse(config.setupCommands().isEmpty());
        assertFalse(config.workloadCommands().isEmpty());
    }

    @Test
    void commentsAreStrippedButCommandsAreNot() throws Exception {
        ProbeConfig config = load();
        for (String command : config.setupCommands()) {
            assertFalse(command.startsWith("#"), "comment leaked into the command list: " + command);
            assertFalse(command.isBlank());
        }
    }

    @Test
    void gamerulesArePlacedBeforeWorldBuildingCommands() throws Exception {
        // Setup must not race the rules meant to hold it steady: spawning
        // entities before doMobSpawning is off lets natural spawns contaminate an
        // otherwise deterministic population.
        List<String> setup = load().setupCommands();
        int lastGamerule = -1;
        int firstSummon = Integer.MAX_VALUE;
        for (int i = 0; i < setup.size(); i++) {
            if (setup.get(i).startsWith("gamerule ")) {
                lastGamerule = i;
            }
            if (setup.get(i).startsWith("summon ") && i < firstSummon) {
                firstSummon = i;
            }
        }
        assertTrue(lastGamerule >= 0, "fixture should contain gamerules");
        assertTrue(firstSummon < Integer.MAX_VALUE, "fixture should contain summons");
        assertTrue(lastGamerule < firstSummon);
    }

    @Test
    void theQueueServesTheCompiledPlanInOrder() throws Exception {
        ProbeConfig config = load();
        CommandQueue queue = new CommandQueue(config.setupCommands(), config.workloadCommands());

        String first = queue.poll();
        assertNotNull(first);
        assertTrue(first.startsWith("gamerule "), "got: " + first);

        // Drain setup, allowing for pacing directives which legitimately return null.
        int polls = 0;
        while (!queue.setupComplete() && polls < 10_000) {
            queue.poll();
            polls++;
        }
        assertTrue(queue.setupComplete(), "setup never completed");
    }

    @Test
    void waitDirectivesArrivedIntactFromThePythonCompiler() throws Exception {
        ProbeConfig config = load();
        boolean hasWait = config.setupCommands().stream()
                .anyMatch(c -> c.startsWith(CommandQueue.WAIT_PREFIX));
        assertTrue(hasWait, "the fixture's trailing settle wait should have compiled through");
    }

    @Test
    void largeFillsWereSplitBeforeReachingTheProbe() throws Exception {
        // Vanilla /fill rejects volumes over 32768. Splitting happens on the
        // Python side, so this checks the probe never receives an oversized one.
        for (String command : load().setupCommands()) {
            if (!command.startsWith("fill ")) {
                continue;
            }
            String[] parts = command.split("\\s+");
            long volume = 1;
            for (int axis = 0; axis < 3; axis++) {
                long from = Long.parseLong(parts[1 + axis]);
                long to = Long.parseLong(parts[4 + axis]);
                volume *= Math.abs(to - from) + 1;
            }
            assertTrue(volume <= 32768, "oversized fill reached the probe: " + command);
        }
    }
}
